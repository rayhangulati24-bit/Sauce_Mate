export const NOT_FOOD_ERROR =
  "That's not a food item. Try searching for something you can eat.";

export function normalizeFoodTerm(term) {
  return String(term || "")
    .trim()
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, "");
}

export function isExperimentalCatalogTerm(term) {
  const normalized = normalizeFoodTerm(term);
  return (
    normalized === "experimental" ||
    normalized === "experimentalpairings" ||
    normalized === "experimentalpairing"
  );
}

