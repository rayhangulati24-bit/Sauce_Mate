export function findLocalFoodMatches(foodDatabase, term) {
  const searchWords = String(term || "")
    .toLowerCase()
    .split(/\s+/)
    .join("");
  if (!searchWords) return [];
  return Object.keys(foodDatabase || {}).filter((key) => {
    if (key === "experimentalPairings") {
      return isExperimentalCatalogTerm(term);
    }
    return key.toLowerCase().includes(searchWords);
  });
}

export function isFoodSearchTerm(term, foodDatabase) {
  const trimmed = String(term || "").trim();
  if (!trimmed) return false;
  if (isExperimentalCatalogTerm(trimmed)) return true;
  if (foodDatabase && findLocalFoodMatches(foodDatabase, trimmed).length > 0) {
    return true;
  }

  const compact = normalizeFoodTerm(trimmed);
  if (!compact) return false;

  const words = trimmed
    .toLowerCase()
    .split(/[^a-z0-9]+/)
    .filter(Boolean);
  if (words.some((word) => FOOD_TERMS.has(word))) return true;
  if (FOOD_TERMS.has(compact)) return true;

  for (const signal of FOOD_TERMS) {
    if (signal.length >= 4 && compact.includes(signal)) return true;
  }
  return false;
}

export function isNotFoodPayload(data) {
  if (!data || typeof data !== "object") return false;
  if (data.notFood === true || data.error === "not_food") return true;
  return Array.isArray(data.suggestions) && data.suggestions.length === 0;
}
